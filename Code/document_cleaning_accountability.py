def remove_word_count_brackets(text):
    """
    Removes any bracketed expression ( (), [], {} ) that contains the phrase 'word count',
    including the brackets themselves. Case-insensitive and handles nested brackets safely
    by matching the outermost pair.
    
    Examples:
      "Some text (word count: 120)" → "Some text "
      "Report [approx. word count: 250]" → "Report "
      "Data {Word Count = 300}" → "Data "
    """
    if not isinstance(text, str):
        return text

    # Pattern matches ( ... ), [ ... ], or { ... } containing 'word count'
    # Uses non-greedy matching and accounts for possible nested brackets by limiting depth
    # This regex assumes brackets are balanced and not deeply nested (typical in prose)
    pattern = r'[\(\[\{][^\)\]\}]*?\bword\s+count\b[^\)\]\}]*?[\)\]\}]'
    
    # Remove all matches, case-insensitive
    cleaned = re.sub(pattern, '', text, flags=re.IGNORECASE)
    
    # Optional: clean up extra whitespace left behind
    cleaned = re.sub(r'\s{2,}', ' ', cleaned)  # Replace multiple spaces with single space
    
    return cleaned
