def split_paragraph_on_soft_break_robust(paragraph: Paragraph):
    """
    Safely splits a paragraph containing one or more soft line breaks ('\n') into multiple paragraphs.

    ⚠️ Skips paragraphs that are part of a bulleted or numbered list to preserve list formatting.
    """
    # Skip if paragraph is a list item (has numbering properties)
    if paragraph._element.xpath('.//w:numPr'):
        return

    text = paragraph.text
    if '\n' not in text:
        return

    # Split on *all* newlines to handle multiple breaks
    lines = [line.strip() for line in text.split('\n') if line.strip()]
    if not lines:
        return

    p_element = paragraph._element
    parent = p_element.getparent()
    if parent is None:
        return

    # Get the document part to access the paragraph factory
    try:
        body_element = paragraph.part.document.element.body
    except AttributeError:
        # Fallback if part/document is not accessible (unlikely in standard use)
        return

    # Replace current paragraph with first line
    paragraph.clear()
    if lines:
        paragraph.add_run(lines[0])

    # Insert new paragraphs for remaining lines
    for line in lines[1:]:
        new_p_element = body_element._new_p()  # Correct way to create new <w:p>
        parent.insert(parent.index(p_element) + 1, new_p_element)
        new_para = Paragraph(new_p_element, paragraph._parent)
        new_para.add_run(line)
        new_para.style = paragraph.style  # Copy style

