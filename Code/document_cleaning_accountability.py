def set_document_footer(doc):
    """
    Sets footer on pages 2+ to:
      CENTER: "CES summary of full academic report"
      RIGHT:  page number
    First page remains blank (logo only).
    Uses direct XML to define tab stops (bypasses python-docx TabStops limitation).
    """
    static_text = """CES summary of full academic report"""

    for section in doc.sections:
        section.different_first_page_header_footer = False
        footer = section.footer
        paragraph = footer.paragraphs[0]
        paragraph.clear()

        # --- Set paragraph alignment to left (tabs will handle positioning) ---
        paragraph.alignment = 0  # Left align base

        # --- Define tab stops via XML (center and right) ---
        page_width = section.page_width
        left_margin = section.left_margin if section.left_margin is not None else Inches(1)
        right_margin = section.right_margin if section.right_margin is not None else Inches(1)
        text_width = page_width - left_margin - right_margin
        center_pos = left_margin + text_width / 8
        right_pos = page_width - right_margin

        # Convert to twentieths of a point (Word's internal unit)
        def in_twips(length):
            return int(length / Inches(1) * 1440)  # 1 inch = 1440 twips

        center_twips = in_twips(center_pos)
        right_twips = in_twips(right_pos)

        # Create <w:tabs> element
        tabs_xml = f'''
            <w:tabs {nsdecls('w')}>
                <w:tab w:val="center" w:pos="{center_twips}"/>
                <w:tab w:val="right" w:pos="{right_twips}"/>
            </w:tabs>
        '''
        tabs_element = parse_xml(tabs_xml)
        paragraph._element.get_or_add_pPr().append(tabs_element)

        # --- Add text with tabs ---
        run = paragraph.add_run()
        run.add_text("\t")  # jump to center tab
        run.add_text(static_text)
        run.add_text("\t")  # jump to right tab

        # --- Add PAGE field ---
        run._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="begin"/>' % nsdecls('w')))
        run._r.append(parse_xml(r'<w:instrText %s xml:space="preserve">PAGE</w:instrText>' % nsdecls('w')))
        run._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="separate"/>' % nsdecls('w')))
        run._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="end"/>' % nsdecls('w')))

        # --- Apply font to all runs ---
        for r in paragraph.runs:
            r.font.name = 'Calibri'
            r.font.size = Pt(11)
            r.font.color.rgb = RGBColor(0x00, 0x00, 0x00)


def add_document_title_as_h3(doc, title_text, font_size=11):
    """
    Adds a title as the first paragraph in the document body,
    styled as Heading 3 with a custom font size (default: 11pt).
    Appears on page 1 only, above all other content.
    """
    if not isinstance(title_text, str) or not title_text.strip():
        return

    try:
        font_size = int(font_size)  # Accept "11" or 11
    except (TypeError, ValueError):
        font_size = 11  # fallback

    # Ensure we insert at the very top of the document body
    if doc.paragraphs and doc.paragraphs[0].text.strip():
        # Create new paragraph and insert at top via XML
        new_para = doc.add_paragraph()
        body = doc.element.body
        body.insert(0, new_para._element)
        paragraph = new_para
    else:
        # Reuse/clear first paragraph
        paragraph = doc.paragraphs[0] if doc.paragraphs else doc.add_paragraph()
        paragraph.clear()

    # Apply Heading 3 style
    paragraph.style = 'Heading 3'

    # Add the title text
    run = paragraph.add_run(title_text.strip())

    # Set font properties
    run.font.size = Pt(font_size)
    run.font.color.rgb= RGBColor(0x00, 0x00, 0x8B)
    run.font.name = 'Calibri'
    run.font.bold = True

    # Ensure spacing is clean
    pf = paragraph.paragraph_format
    pf.space_after = Pt(12)
    pf.space_before = Pt(0)
