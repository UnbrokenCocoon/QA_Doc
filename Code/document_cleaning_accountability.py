def remove_existing_header_text(doc, header_text, threshold=90):
    """
    Removes any paragraph in the document body that closely matches header_text.
    Uses fuzzy matching to catch minor variations.
    """
    paras_to_remove = []
    normalized_target = normalize_for_comparison(header_text)

    for para in doc.paragraphs:
        if not para.text.strip():
            continue
        normalized_para = normalize_for_comparison(para.text)
        score = fuzz.token_sort_ratio(normalized_target, normalized_para)
        if score >= threshold:
            paras_to_remove.append(para)

    for para in paras_to_remove:
        p_elem = para._element
        parent = p_elem.getparent()
        if parent is not None and p_elem in parent:
            parent.remove(p_elem)


