def merge_adjacent_citations_in_paragraph(text):
    parts = re.split(r'(\([^)]*\))', text)
    if len(parts) < 3:
        return text
    result = []
    i = 0
    while i < len(parts):
        if (parts[i].startswith('(') and i + 2 < len(parts) and parts[i+2].startswith('(')):
            if (re.search(r'\b(pp?\.?)\b', parts[i], re.IGNORECASE) and re.search(r'\b(pp?\.?)\b', parts[i+2], re.IGNORECASE)):
                sep = parts[i+1] if i+1 < len(parts) else ''
                if re.fullmatch(r'\s*\.\s*', sep) or re.fullmatch(r'\s*', sep):
                    merged = parts[i][:-1] + ', ' + parts[i+2][1:]
                    result.append(merged)
                    i += 3
                    continue
        result.append(parts[i])
        i += 1
    return ''.join(result)

def replace_semicolon_in_citations(text):
    def replacer(m):
        s = m.group(0)
        return s.replace(';', ',') if re.search(r'\b(pp?\.?)\b', s, re.IGNORECASE) else s
    return re.sub(r'\([^)]*\)', replacer, text)

def expand_implicit_page_prefixes(text):
    def process(m):
        content = m.group(0)
        inner = content[1:-1].strip()
        parts = [p.strip() for p in inner.split(',')]
        if len(parts) < 2:
            return content
        first = parts[0]
        if not re.match(r'^\s*(pp?\.)(.*)', first, re.IGNORECASE):
            return content
        prefix = re.match(r'^\s*(pp?\.).*', first, re.IGNORECASE).group(1)
        new_parts = [first]
        for part in parts[1:]:
            if re.match(r'^[\d–\-]', part):
                new_parts.append(prefix + part)
            else:
                new_parts.append(part)
        return '(' + ', '.join(new_parts) + ')'
    return re.sub(r'\([^)]*\)', process, text)

def normalize_page_citations_in_parentheses(text):
    def process(m):
        content = m.group(0)
        inner = content[1:-1]
        parts = [p.strip() for p in inner.split(',')]
        new_parts = []
        for part in parts:
            if re.search(r'\bp\.\s*\d+\s*[-–]\s*\d+', part, re.IGNORECASE):
                part = re.sub(r'\bp\.', 'pp.', part, count=1, flags=re.IGNORECASE)
            new_parts.append(part)
        return '(' + ', '.join(new_parts) + ')'
    return re.sub(r'\([^)]*\)', process, text)

def normalize_citation_whitespace(text):
    def process(m):
        content = m.group(0)
        if not re.search(r'\b(pp?\.?)\b', content, re.IGNORECASE):
            return content
        inner = content[1:-1]
        parts = [p.strip() for p in inner.split(',')]
        clean_parts = []
        for part in parts:
            if part:
                part = re.sub(r'\b(pp?\.?)\s*(\d)', r'\1 \2', part, flags=re.IGNORECASE)
                part = re.sub(r'\s+', ' ', part).strip()
                clean_parts.append(part)
        return '(' + ', '.join(clean_parts) + ')'
    return re.sub(r'\([^)]*\)', process, text)

def deduplicate_page_citations(text):
    def process(m):
        content = m.group(0)
        if not re.search(r'\b(pp?\.?)\b', content, re.IGNORECASE):
            return content
        inner = content[1:-1]
        parts = [p.strip() for p in inner.split(',')]
        seen = set()
        unique = []
        for p in parts:
            if p and p not in seen:
                unique.append(p)
                seen.add(p)
        return '(' + ', '.join(unique) + ')'
    return re.sub(r'\([^)]*\)', process, text)

