def run_contains_field(run):
    """Check if run contains a Word field (e.g., page number, date)."""
    return bool(run._element.xpath('.//w:fldChar | .//w:instrText'))

def clean_word_document(input_path):
    """
    Applies text-level citation and language normalization fixes to a .docx file.
    Skips runs containing fields (e.g., page numbers) to preserve them.
    """
    doc = Document(input_path)

    cleanup_functions = [
    remove_word_count_brackets,  # ← Add this first
    de_americanise_text,
    deduplicate_page_citations,
    normalize_page_citations_in_parentheses,
    expand_implicit_page_prefixes,
    replace_semicolon_in_citations,
    merge_adjacent_citations_in_paragraph,
    normalize_citation_whitespace,
]

    # Process body paragraphs
    for para in doc.paragraphs:
        for run in para.runs:
            if run_contains_field(run):
                continue  # ← Skip page numbers, dates, etc.
            if run.text.strip():
                cleaned_text = run.text
                for func in cleanup_functions:
                    cleaned_text = func(cleaned_text)
                run.text = cleaned_text

    # Process headers and footers
    for section in doc.sections:
        for header_footer in (section.header, section.footer):
            for para in header_footer.paragraphs:
                for run in para.runs:
                    if run_contains_field(run):
                        continue  # ← Preserve page numbers!
                    if run.text.strip():
                        cleaned_text = run.text
                        for func in cleanup_functions:
                            cleaned_text = func(cleaned_text)
                        run.text = cleaned_text

    doc.save(input_path)
