def clean_text(text):
    if not isinstance(text, str):
        return ""
    return unicodedata.normalize('NFKC', text).strip()

def normalize_for_comparison(text):
    if not isinstance(text, str):
        return ""
    text = unicodedata.normalize('NFKC', text)
    text = re.sub(r'[-–—]', '-', text)
    text = ' '.join(text.split())
    return text.lower()

def is_candidate_subheading(text):
    text = clean_text(text)
    if not text:
        return False
    words = [w for w in text.split() if w]
    if len(words) == 0 or len(words) > MAX_HEADING_WORDS:
        return False
    if re.match(r"^\(.*[Cc]ount.*\)$", text):
        return False
    if text.endswith(('.', '!', '?')):
        return False
    if EXCLUDE_START_PATTERNS.match(text):
        return False
    return True

def get_best_match(actual, expected_list, threshold=THRESHOLD):
    if not isinstance(actual, str):
        return None, 0

    norm_actual = normalize_for_comparison(actual)
    best_score, best_exp = 0, None

    for exp in expected_list:
        if not isinstance(exp, str):
            continue
        norm_exp = normalize_for_comparison(exp)
        score = fuzz.token_set_ratio(norm_actual, norm_exp)
        if score > best_score:
            best_score, best_exp = score, exp

    if best_score >= threshold:
        return best_exp, best_score
    return None, best_score

