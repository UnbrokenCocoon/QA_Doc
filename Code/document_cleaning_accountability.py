def clean_text(text):
    if not isinstance(text, str):
        return ""
    return unicodedata.normalize('NFKC', text).strip()

def normalize_for_comparison(text):
    if not isinstance(text, str):
        return ""
    text = unicodedata.normalize('NFKC', text)
    text = re.sub(r'[-–—]', '-', text)
    text = ' '.join(text.split())
    return text.lower()

def is_candidate_subheading(text):
    text = clean_text(text)
    if not text:
        return False
    words = [w for w in text.split() if w]
    if len(words) == 0 or len(words) > MAX_HEADING_WORDS:
        return False
    if re.match(r"^\(.*[Cc]ount.*\)$", text):
        return False
    if text.endswith(('.', '!', '?')):
        return False
    if EXCLUDE_START_PATTERNS.match(text):
        return False
    return True

def analyze_document(docx_path):
    doc = Document(docx_path)
    rq_pattern = re.compile(r"^RQ\s*[1-6]\b", re.IGNORECASE)
    timeline_pattern = re.compile(r".*Timeline.*Accountability.*Reform", re.IGNORECASE)

    current_section = None
    in_main_content = False
    actual_rq_titles = {}
    actual_by_rq = defaultdict(list)

    for para in doc.paragraphs:
        raw_text = para.text
        if not raw_text or not raw_text.strip():
            continue

        cleaned_full = clean_text(raw_text)

        if rq_pattern.match(cleaned_full):
            match_num = re.search(r'RQ\s*([1-6])', cleaned_full, re.IGNORECASE)
            if match_num:
                rq_key = f"RQ{match_num.group(1)}"
                expected_title = expected_rq_titles[rq_key]
                if normalize_for_comparison(cleaned_full).startswith(normalize_for_comparison(expected_title)):
                    actual_rq_titles[rq_key] = expected_title
                else:
                    actual_rq_titles[rq_key] = cleaned_full
                current_section = rq_key
                in_main_content = True
            continue

        if timeline_pattern.search(cleaned_full):
            current_section = "Timeline"
            in_main_content = True
            continue

        if not in_main_content or current_section is None:
            continue

        first_line = raw_text.split('\n')[0]
        first_line_clean = clean_text(first_line)

        if is_candidate_subheading(first_line_clean):
            actual_by_rq[current_section].append(first_line_clean)

    return actual_by_rq, actual_rq_titles

def compute_metrics(actual_by_rq, actual_rq_titles):
    # RQ Title correctness
    rq_title_correct = sum(
        1 for rq, exp in expected_rq_titles.items()
        if actual_rq_titles.get(rq) == exp
    )

    total_expected = sum(len(v) for k, v in expected_structure.items() if k != "Timeline")
    valid_matches = 0
    needs_review = 0

    # Deduplicated matching
    for rq in ["RQ1", "RQ2", "RQ3", "RQ4", "RQ5", "RQ6"]:
        expected_list = expected_structure[rq]
        actual_list = actual_by_rq.get(rq, [])
        matches = []
        for actual in actual_list:
            for exp in expected_list:
                score = fuzz.token_set_ratio(actual, exp)
                matches.append((score, actual, exp))
        matches.sort(key=lambda x: x[0], reverse=True)

        assigned_expected = set()
        reported_actuals = set()

        for score, actual, exp in matches:
            if actual in reported_actuals or exp in assigned_expected:
                continue
            if score >= THRESHOLD:
                valid_matches += 1
                assigned_expected.add(exp)
                reported_actuals.add(actual)
            else:
                # Only count once per actual
                if actual not in reported_actuals:
                    needs_review += 1
                    reported_actuals.add(actual)

        # Count unreported actuals as needs_review
        for actual in actual_list:
            if actual not in reported_actuals:
                needs_review += 1

    missing = total_expected - valid_matches
    total_detected = sum(len(v) for v in actual_by_rq.values() if v and not v[0].startswith("Timeline"))

    return {
        "RQ_Titles_Correct": rq_title_correct,
        "Total_Expected_Subheadings": total_expected,
        "Total_Detected": total_detected,
        "Valid_Matches": valid_matches,
        "Needs_Review": needs_review,
        "Missing": missing
    }

