def merge_adjacent_citations_in_paragraph(text):
    """Merge consecutive (p./pp.) citations separated by '. ' or space."""
    parts = re.split(r'(\([^)]*\))', text)
    if len(parts) < 3:
        return text

    result = []
    i = 0
    while i < len(parts):
        if (parts[i].startswith('(') and
            i + 2 < len(parts) and
            parts[i+2].startswith('(')):
            if (re.search(r'\b(pp?\.?)\b', parts[i], re.IGNORECASE) and
                re.search(r'\b(pp?\.?)\b', parts[i+2], re.IGNORECASE)):
                sep = parts[i+1] if i+1 < len(parts) else ''
                if re.fullmatch(r'\s*\.\s*', sep) or re.fullmatch(r'\s*', sep):
                    merged = parts[i][:-1] + ', ' + parts[i+2][1:]
                    result.append(merged)
                    i += 3
                    continue
        result.append(parts[i])
        i += 1
    return ''.join(result)

def replace_semicolon_in_citations(text):
    """Replace ';' with ',' inside parentheses only if 'p.' or 'pp.' is present."""
    def replacer(match):
        content = match.group(0)
        if re.search(r'\b(pp?\.?)\b', content, re.IGNORECASE):
            return content.replace(';', ',')
        return content
    return re.sub(r'\([^)]*\)', replacer, text)

def expand_implicit_page_prefixes(text):
    """Expand (p.6, 7) → (p.6, p.7) inside parentheses."""
    def process_group(match):
        content = match.group(0)
        inner = content[1:-1].strip()
        parts = [part.strip() for part in inner.split(',')]
        if len(parts) < 2:
            return content

        first = parts[0]
        p_match = re.match(r'^\s*(pp?\.)(.*)', first, re.IGNORECASE)
        if not p_match:
            return content

        prefix = p_match.group(1)
        new_parts = [first]
        for part in parts[1:]:
            if re.match(r'^[\d–\-]', part):
                new_parts.append(prefix + part)
            else:
                new_parts.append(part)
        return '(' + ', '.join(new_parts) + ')'

    return re.sub(r'\([^)]*\)', process_group, text)

def normalize_page_citations_in_parentheses(text):
    """Fix p. → pp. for page ranges inside parentheses, per fragment."""
    def process_paren_group(match):
        content = match.group(0)
        inner = content[1:-1]
        parts = [part.strip() for part in inner.split(',')]
        new_parts = []
        for part in parts:
            if re.search(r'\bp\.\s*\d+\s*[-–]\s*\d+', part, re.IGNORECASE):
                new_part = re.sub(r'\bp\.', 'pp.', part, count=1, flags=re.IGNORECASE)
                new_parts.append(new_part)
            else:
                new_parts.append(part)
        new_inner = ', '.join(new_parts)
        return '(' + new_inner + ')'
    return re.sub(r'\([^)]*\)', process_paren_group, text)

def normalize_citation_whitespace(text):
    """Normalize spacing in page citations inside parentheses."""
    def process_group(match):
        content = match.group(0)
        if not re.search(r'\b(pp?\.?)\b', content, re.IGNORECASE):
            return content
        inner = content[1:-1]
        parts = [part.strip() for part in inner.split(',')]
        clean_parts = []
        for part in parts:
            if not part:
                continue
            part = re.sub(r'\b(pp?\.?)\s*(\d)', r'\1 \2', part, flags=re.IGNORECASE)
            part = re.sub(r'\s+', ' ', part)
            clean_parts.append(part.strip())
        new_inner = ', '.join(clean_parts)
        return '(' + new_inner + ')'
    return re.sub(r'\([^)]*\)', process_group, text)

def deduplicate_page_citations(text):
    """Remove duplicate page references inside parentheses."""
    def process_group(match):
        content = match.group(0)
        if not re.search(r'\b(pp?\.?)\b', content, re.IGNORECASE):
            return content
        inner = content[1:-1]
        parts = [part.strip() for part in inner.split(',')]
        seen = set()
        unique_parts = []
        for part in parts:
            if part and part not in seen:
                unique_parts.append(part)
                seen.add(part)
        new_inner = ', '.join(unique_parts)
        return '(' + new_inner + ')'
    return re.sub(r'\([^)]*\)', process_group, text)

