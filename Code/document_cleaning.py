def clean_word_document(file_path):

    document = None
    try:
        # --- 1. PREPARE DOCUMENT AND JURISDICTION ---
        filename = os.path.basename(file_path)
        jurisdiction_name = "Jurisdiction Unknown"

        for j in JURISDICTIONS:
            if j.lower() in filename.lower():
                jurisdiction_name = j
                break

        RQ_FULL_TITLES = [t.replace("X", jurisdiction_name) for t in RQ_TEMPLATES]
        HEADER_TEXT = f"{jurisdiction_name} Curriculum – RQ Aligned Summary"

        # Open the document
        document = Document(file_path)

        # ------------------------------------------------------------------
        # --- 1.5. AUTOMATIC SUBHEADING IDENTIFICATION ---
        # ------------------------------------------------------------------

        texts = []
        for i, paragraph in enumerate(document.paragraphs, 1):
            text = paragraph.text.strip()
            if not text:
                continue
            else:
                words = word_tokenize(text)
                # Filter for short phrases (less than 13 words)
                if len(words) < 13:
                    texts.append(text)

        identified_subheadings = list(set([text for text in texts if text not in RQ_TEMPLATES]))

        # ------------------------------------------------------------------
        # --- 1.6. FALLBACK SUBHEADING DETECTION (SPLIT BY \n, NO FULL STOPS) ---
        # ------------------------------------------------------------------
        fallback_subheadings = []
        for paragraph in document.paragraphs:
            full_text = paragraph.text
            # Split by newline to handle multi-line paragraphs
            lines = full_text.split('\n')
            for line in lines:
                stripped_line = line.strip()
                if not stripped_line:
                    continue
                # Skip if contains a full stop (to avoid short sentences)
                if '.' in stripped_line:
                    continue
                # Tokenize and check word count
                words = word_tokenize(stripped_line)
                if len(words) < 13:
                    fallback_subheadings.append(stripped_line)

        # Merge with previously identified subheadings
        identified_subheadings = list(set(identified_subheadings + fallback_subheadings))
        # ------------------------------------------------------------------

        STANDARD_SUBHEADINGS = BASE_SUBHEADINGS.copy()
        STANDARD_SUBHEADINGS.extend(identified_subheadings)

        # ------------------------------------------------------------------

        # --- 2. APPLY DOCUMENT-WIDE STYLES AND CLEANUP ---

        normal_style = document.styles['Normal']
        set_style_formatting(normal_style)

        # NEW: List to safely hold paragraphs for removal
        paragraphs_to_remove = []

        for paragraph in document.paragraphs:
            raw_text = paragraph.text

            # --- NEW: Merge adjacent citation groups like "(p. X). (p. Y)" ---
            raw_text = merge_adjacent_citations_in_paragraph(raw_text)
            paragraph.text = raw_text

            p_text = raw_text.strip()

            # --- Check 0: Remove paragraphs that are empty or only whitespace/newlines ---
            if p_text == '':
                paragraphs_to_remove.append(paragraph)
                continue

            # --- Check 1: Mark for Removal (Header Text) ---
            if HEADER_TEXT in p_text:
                paragraphs_to_remove.append(paragraph)
                continue # Skip all other processing for this paragraph

            # --- Check 2: Apply Subheading Formatting ---

            # Remove double newlines within paragraph (e.g., from double soft returns)
            if '\n\n' in paragraph.text:
                paragraph.text = paragraph.text.replace('\n\n', ' ')

            # Text Cleanup Operations (only runs on paragraphs NOT marked for removal)
            punctuation_marks = [".", ",", ":", ";", "!", "?", ")", "]"]
            for punct in punctuation_marks:
                replace_text_in_paragraph(paragraph, " " + punct, punct)

            # Note: The original code used a non-breaking space ( ). Corrected to standard space.
            replace_text_in_paragraph(paragraph, "  ", " ")

            # --- Fix semicolons in citations (only if p. or pp. present) ---
            if '(' in paragraph.text and ';' in paragraph.text:
                new_text = replace_semicolon_in_citations(paragraph.text)
                if new_text != paragraph.text:
                    paragraph.text = new_text

            # --- Expand implicit page prefixes: (p.6, 7) → (p.6, p.7) ---
            if '(' in paragraph.text and re.search(r'\([pP][pP]?\.\s*\d', paragraph.text):
                new_text = expand_implicit_page_prefixes(paragraph.text)
                if new_text != paragraph.text:
                    paragraph.text = new_text

            # --- Normalize p. → pp. for page ranges in citations ---
            if '(' in paragraph.text and 'p.' in paragraph.text:
                new_text = normalize_page_citations_in_parentheses(paragraph.text)
                if new_text != paragraph.text:
                    paragraph.text = new_text

            # --- Normalize whitespace in citations ---
            if '(' in paragraph.text and re.search(r'\([pP][pP]?\.', paragraph.text):
                new_text = normalize_citation_whitespace(paragraph.text)
                if new_text != paragraph.text:
                    paragraph.text = new_text

            # --- Deduplicate repeated page refs like (p.15, p.15) ---
            if '(' in paragraph.text and re.search(r'\([pP][pP]?\.', paragraph.text):
                new_text = deduplicate_page_citations(paragraph.text)
                if new_text != paragraph.text:
                    paragraph.text = new_text

            # --- De-Americanise spelling ---
            new_text = de_americanise_text(paragraph.text)
            if new_text != paragraph.text:
                paragraph.text = new_text


            if p_text in RQ_FULL_TITLES:
                for run in paragraph.runs:
                    run.font.bold = True
                    run.font.color.rgb = COLOR_DARK_BLUE_RGB
            # CHECK AGAINST THE DYNAMICALLY GENERATED LIST (NOW EXACT MATCH)
            elif p_text in STANDARD_SUBHEADINGS:
                for run in paragraph.runs:
                    run.font.bold = True
                    run.font.color.rgb = COLOR_BLACK_RGB

        # --- NEW STEP: Remove the marked paragraphs AFTER the iteration loop ---
        for paragraph in paragraphs_to_remove:
            # Use the robust XML removal method to delete the paragraph element
            paragraph._element.getparent().remove(paragraph._element)

        # --- 3. SETUP FIRST PAGE HEADER (FIXED LOGIC) ---

        section = document.sections[0]
        section.different_first_page_header_footer = True

        first_page_header = section.first_page_header
        primary_header = section.header

        # CRITICAL FIX: Ensure header objects exist before clearing
        if not first_page_header.paragraphs:
            first_page_header.add_paragraph()
        if not primary_header.paragraphs:
            primary_header.add_paragraph()

        # Clear all existing content now that the XML links are guaranteed
        clear_header_content(first_page_header)
        clear_header_content(primary_header)

        # --- Set the New First Page Header ---
        header_para = first_page_header.add_paragraph()
        header_para.text = HEADER_TEXT

        # Apply header formatting
        run = header_para.runs[0]
        run.font.name = "Calibri"
        run.font.size = Pt(14)
        run.font.bold = True
        run.font.color.rgb = COLOR_DARK_BLUE_RGB


        # --- 4. SAVE AND CLOSE ---
        document.save(file_path)
        print(f"✅ Successfully cleaned and formatted (python-docx): {os.path.basename(file_path)}")

    except Exception as e:
        error_msg = str(e)
        if document is None:
            error_msg = f"Failed to open document: {e}"

        print(f"❌ Error processing {os.path.basename(file_path)}: {error_msg}")


# --- Batch Function (Unchanged) ---
def batch_process_docs_python(directory_path):
    """Processes all .docx files in a directory using python-docx."""

    print(f"Starting python-docx process to clean documents in: {directory_path}")

    if not os.path.isdir(directory_path):
        print(f"Error: Directory not found at {directory_path}")
        return

    try:
        for filename in os.listdir(directory_path):
            if filename.endswith(".docx") and not filename.startswith("~"):
                full_path = os.path.join(directory_path, filename)
                clean_word_document(full_path)

    except Exception as e:
        print(f"\nFATAL ERROR during batch processing: {e}")

    finally:
        print("\nBatch process complete.")


